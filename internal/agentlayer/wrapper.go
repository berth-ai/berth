package agentlayer

import (
	"fmt"
	"strings"
)

// wrapperScript returns a POSIX sh wrapper that sets each of keys from
// keysPath (unless the environment already has it) and execs target. Values
// are taken with parameter expansion, never evaluated, so any byte that
// ValidKeyValue allows passes through unchanged.
func wrapperScript(target, keysPath string, keys []string) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by berth; do not edit.\n")
	if len(keys) > 0 {
		fmt.Fprintf(&b, "if [ -r %s ]; then\n", keysPath)
		b.WriteString("  while IFS= read -r berth_line; do\n")
		b.WriteString("    case ${berth_line%%=*} in\n")
		for _, k := range keys {
			fmt.Fprintf(&b, "      %s) [ -n \"${%s+set}\" ] || export %s=\"${berth_line#*=}\" ;;\n", k, k, k)
		}
		b.WriteString("    esac\n")
		fmt.Fprintf(&b, "  done <%s\n", keysPath)
		b.WriteString("  unset berth_line\nfi\n")
	}
	fmt.Fprintf(&b, "exec %s \"$@\"\n", target)
	return b.String()
}
