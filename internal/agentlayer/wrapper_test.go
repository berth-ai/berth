func TestWrapperWithoutKeys(t *testing.T) {
	got := wrapperScript("/opt/agents/current/bin/opencode", "/k/agents.env", nil, false)
	want := "#!/bin/sh\n# Generated by berth; do not edit.\nexec /opt/agents/current/bin/opencode \"$@\"\n"
	if got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
}

// runWrapper executes a generated wrapper whose target prints two env vars.
func runWrapper(t *testing.T, keys string, env []string) string {
	t.Helper()
	dir := t.TempDir()
	target := filepath.Join(dir, "target")
	os.WriteFile(target, []byte("#!/bin/sh\nprintf '%s|%s|%s' \"$A_KEY\" \"${B_KEY-unset}\" \"$1\"\n"), 0o755)
	keysPath := filepath.Join(dir, "agents.env")
	os.WriteFile(keysPath, []byte(keys), 0o640)
	w := filepath.Join(dir, "wrapper")
	os.WriteFile(w, []byte(wrapperScript(target, keysPath, []string{"A_KEY", "B_KEY"}, false)), 0o755)
	cmd := exec.Command(w, "arg one")
	cmd.Env = append([]string{"PATH=/usr/bin:/bin"}, env...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("%v: %s", err, out)
	}
	return string(out)
}

func TestWrapperPassesKeyVerbatim(t *testing.T) {
	value := "a$b`c;d=e=="
	if got := runWrapper(t, "A_KEY="+value+"\nC_KEY=other\n", nil); got != value+"|unset|arg one" {
		t.Errorf("got %q", got)
	}
}

func TestEnvironmentWins(t *testing.T) {
	if got := runWrapper(t, "A_KEY=from-panel\nB_KEY=b\n", []string{"A_KEY=mine"}); got != "mine|b|arg one" {
		t.Errorf("got %q", got)
	}
}

func TestWrapperWithoutKeysFile(t *testing.T) {
	dir := t.TempDir()
	target := filepath.Join(dir, "target")
	os.WriteFile(target, []byte("#!/bin/sh\necho ok\n"), 0o755)
	w := filepath.Join(dir, "w")
	os.WriteFile(w, []byte(wrapperScript(target, filepath.Join(dir, "missing.env"), []string{"A_KEY"}, false)), 0o755)
	out, err := exec.Command(w).CombinedOutput()
	if err != nil || strings.TrimSpace(string(out)) != "ok" {
		t.Errorf("%v %q", err, out)
	}
}

func TestAgentWrapperExportsMCPTokens(t *testing.T) {
	dir := t.TempDir()
	target := filepath.Join(dir, "target")
	os.WriteFile(target, []byte("#!/bin/sh\nprintf '%s|%s|%s' \"$MCP_C7_TOKEN\" \"${MCP_BAD-unset}\" \"${OTHER-unset}\"\n"), 0o755)
	keys := filepath.Join(dir, "agents.env")
	os.WriteFile(keys, []byte("MCP_C7_TOKEN=a$b c\nMCP_BAD=x\nOTHER=y\nMCP_a;b_TOKEN=z\n"), 0o640)
	w := filepath.Join(dir, "w")
	os.WriteFile(w, []byte(wrapperScript(target, keys, []string{"A_KEY"}, true)), 0o755)
	cmd := exec.Command(w)
	cmd.Env = []string{"PATH=/usr/bin:/bin"}
	out, err := cmd.CombinedOutput()
	if err != nil || string(out) != "a$b c|unset|unset" {
		t.Errorf("%v %q", err, out)
	}
	// Servers' own wrappers do not get the tokens.
	if strings.Contains(wrapperScript(target, keys, []string{"A_KEY"}, false), "MCP_") {
		t.Error("a server wrapper exports MCP tokens")
	}
}

func TestAgentWrapperKeepsASetToken(t *testing.T) {
	dir := t.TempDir()
	target := filepath.Join(dir, "target")
	os.WriteFile(target, []byte("#!/bin/sh\nprintf '%s|%s' \"$MCP_C7_TOKEN\" \"$MCP_GH_TOKEN\"\n"), 0o755)
	keys := filepath.Join(dir, "agents.env")
	os.WriteFile(keys, []byte("MCP_C7_TOKEN=from-berth\nMCP_GH_TOKEN=gh\n"), 0o640)
	w := filepath.Join(dir, "w")
	os.WriteFile(w, []byte(wrapperScript(target, keys, nil, true)), 0o755)
	cmd := exec.Command(w)
	cmd.Env = []string{"PATH=/usr/bin:/bin", "MCP_C7_TOKEN=from-workspace"}
	out, err := cmd.CombinedOutput()
	if err != nil || string(out) != "from-workspace|gh" {
		t.Errorf("%v %q", err, out)
	}
}
