package agentstore

import (
	"encoding/json"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

var (
	binName   = regexp.MustCompile(`^[A-Za-z0-9._-]+$`)
	binTarget = regexp.MustCompile(`^[A-Za-z0-9@._/+-]+$`)
)

// wrapperHead resolves the wrapper's real version directory, so a session
// started before a flip keeps its own Node tree (and Chromium).
const (
	wrapperHead = "#!/bin/sh\n# Generated by berth; do not edit.\n" +
		"version_dir=$(dirname \"$(dirname \"$(readlink -f \"$0\")\")\")\n"
	browsersLine = "export PLAYWRIGHT_BROWSERS_PATH=\"$version_dir/ms-playwright\"\n"
)

// WriteWrappers writes dir/bin/<name> for every bin declared by the direct
// dependencies deps and returns the bin names, sorted. browsers adds
// PLAYWRIGHT_BROWSERS_PATH; registry agents install no Chromium.
func WriteWrappers(dir string, deps []string, browsers bool) ([]string, error) {
	binDir := filepath.Join(dir, "bin")
	if err := os.MkdirAll(binDir, 0o755); err != nil {
		return nil, err
	}
	owner := map[string]string{}
	for _, dep := range slices.Sorted(slices.Values(deps)) {
		bins, err := packageBins(filepath.Join(dir, "node_modules", filepath.FromSlash(dep)))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", dep, err)
		}
		for _, name := range slices.Sorted(maps.Keys(bins)) {
			target := path.Clean(bins[name])
			if !binName.MatchString(name) || name == "." || name == ".." {
				return nil, fmt.Errorf("%s declares invalid bin name %q", dep, name)
			}
			if !binTarget.MatchString(target) || strings.HasPrefix(target, "..") || path.IsAbs(target) {
				return nil, fmt.Errorf("%s declares invalid bin target %q", dep, bins[name])
			}
			if prev, ok := owner[name]; ok {
				return nil, fmt.Errorf("bin %q is declared by both %s and %s", name, prev, dep)
			}
			owner[name] = dep
			script := wrapperHead
			if browsers {
				script += browsersLine
			}
			script += fmt.Sprintf("exec \"$version_dir/%s\" \"$@\"\n", path.Join("node_modules", dep, target))
			if err := os.WriteFile(filepath.Join(binDir, name), []byte(script), 0o755); err != nil {
				return nil, err
			}
		}
	}
	return slices.Sorted(maps.Keys(owner)), nil
}

// PackageBins returns the bins dependency dep declares in versionDir.
func PackageBins(versionDir, dep string) (map[string]string, error) {
	return packageBins(filepath.Join(versionDir, "node_modules", filepath.FromSlash(dep)))
}

func packageBins(pkgDir string) (map[string]string, error) {
	var p struct {
		Name string          `json:"name"`
		Bin  json.RawMessage `json:"bin"`
	}
	if err := readJSON(filepath.Join(pkgDir, "package.json"), &p); err != nil {
		return nil, err
	}
	if len(p.Bin) == 0 {
		return nil, nil
	}
	var single string
	if err := json.Unmarshal(p.Bin, &single); err == nil {
		return map[string]string{path.Base(p.Name): single}, nil
	}
	var many map[string]string
	if err := json.Unmarshal(p.Bin, &many); err != nil {
		return nil, fmt.Errorf("package.json bin: %w", err)
	}
	return many, nil
}

// Seal makes dir root-owned (when chownRoot) and not writable by group or
// others, so agent self-updaters cannot modify an installed version.
func Seal(dir string, chownRoot bool) error {
	return filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if chownRoot {
			if err := os.Lchown(p, 0, 0); err != nil {
				return err
			}
		}
		if d.Type()&fs.ModeSymlink != 0 {
			return nil
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		return os.Chmod(p, info.Mode().Perm()&^0o022)
	})
}
